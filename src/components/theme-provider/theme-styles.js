import { media } from '@/utils/style';
import { themes, tokens } from './theme';

const GothamBoldItalic = '/assets/fonts/gotham-bold-italic.woff2';
const GothamBold = '/assets/fonts/gotham-bold.woff2';
const GothamBookItalic = '/assets/fonts/gotham-book-italic.woff2';
const GothamBook = '/assets/fonts/gotham-book.woff2';
const GothamMediumItalic = '/assets/fonts/gotham-medium-italic.woff2';
const GothamMedium = '/assets/fonts/gotham-medium.woff2';
const IPAGothic = '/assets/fonts/ipa-gothic.woff2';

/**
 * Squeeze out spaces and newlines
 */
export function squish(styles) {
  return styles.replace(/\s\s+/g, ' ');
}

/**
 * Transform theme token objects into CSS custom property strings
 */
export function createThemeProperties(theme) {
  return squish(
    Object.keys(theme)
      .map(key => `--${key}: ${theme[key]};`)
      .join('\n\n')
  );
}

/**
 * Transform theme tokens into a React CSSProperties object
 */
export function createThemeStyleObject(theme) {
  let style = {};

  for (const key of Object.keys(theme)) {
    style[`--${key}`] = theme[key];
  }

  return style;
}

/**
 * Generate media queries for tokens
 */
export function createMediaTokenProperties() {
  return squish(
    Object.keys(media)
      .map(key => {
        return `
        @media (max-width: ${media[key]}px) {
          :root {
            ${createThemeProperties(tokens[key])}
          }
        }
      `;
      })
      .join('\n')
  );
}

const layerStyles = squish(`
  @layer theme, base, components, layout;
`);

const tokenStyles = squish(`
  :root {
    ${createThemeProperties(tokens.base)}
  }

  ${createMediaTokenProperties()}

  [data-theme='dark'] {
    ${createThemeProperties(themes.dark)}
  }

  [data-theme='light'] {
    ${createThemeProperties(themes.light)}
  }
`);

